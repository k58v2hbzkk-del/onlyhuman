// Writes web/contracts.js with ABI + bytecode so the phone deploy page works without a laptop.
const fs = require("fs");
const path = require("path");
const read = (p) => JSON.parse(fs.readFileSync(path.join(__dirname, "..", "artifacts", p), "utf8"));
const oh = read("contracts/OnlyHuman.sol/OnlyHuman.json");
const usd = read("contracts/test/MockUSD.sol/MockUSD.json");
const out = `// Generated by scripts/export-abi.js — do not edit by hand.
window.OH_CONTRACTS = ${JSON.stringify({
  OnlyHuman: { abi: oh.abi, bytecode: oh.bytecode },
  TestUSD: { abi: usd.abi, bytecode: usd.bytecode },
})};
`;
fs.writeFileSync(path.join(__dirname, "..", "web", "contracts.js"), out);
console.log("wrote web/contracts.js", (out.length / 1024).toFixed(1) + "KB");
